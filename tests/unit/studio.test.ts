import { describe, it, expect } from 'vitest';
import { parseSpec, fallbackSpec, extractObject } from '../../web/src/ai/studio/spec';
import { renderPage, esc } from '../../web/src/ai/studio/render';
import { claudeCodePrompt } from '../../web/src/ai/studio/generate';

const good = { title: 'Calm Yoga', tagline: 'Small classes.', palette: 'forest', cta: 'Book', sections: [
  { kind: 'pricing', heading: 'Prices', items: [{ title: 'Drop-in', text: 'One class; Mat included', meta: '€15' }] },
  { kind: 'contact', heading: 'Contact', items: [] }] };

describe('studio spec repair', () => {
  it('reads JSON wrapped in fences and chatter', () => {
    const s = parseSpec('Sure! Here it is:\n```json\n' + JSON.stringify(good) + '\n```\nEnjoy');
    expect(s?.title).toBe('Calm Yoga');
    expect(s?.sections[0].items[0].meta).toBe('€15');
  });
  it('repairs trailing commas, truncation, wrong types and unknown values', () => {
    expect(parseSpec('{"title":"A","tagline":"B","sections":[{"kind":"faq","heading":"Q","items":[{"title":"x","text":"y"},],},]}')?.sections[0].kind).toBe('faq');
    const t = parseSpec('{"title":"Cut","tagline":"short","palette":"neon","sections":[{"kind":"WIDGET","heading":"H","items":[{"title":5,"text":"ok"');
    expect(t?.palette).toBe('ember');
    expect(t?.sections[0].kind).toBe('features');
    expect(t?.sections[0].items[0].title).toBe('5');
  });
  it('returns null for unusable answers and builds a fallback page from the brief', () => {
    expect(parseSpec('I cannot do that.')).toBeNull();
    expect(extractObject('no json')).toBeNull();
    const f = fallbackSpec('A bakery in Porto. Fresh bread daily.');
    expect(f.title).toBe('Bakery in Porto');
    expect(f.sections.some((s) => s.kind === 'contact')).toBe(true);
  });
});

describe('studio renderer', () => {
  it('escapes everything the model writes', () => {
    const evil = parseSpec(JSON.stringify({ ...good, title: '<script>alert(1)</script>', tagline: '"><img src=x onerror=alert(1)>', sections: [{ kind: 'cards', heading: "</style><script>x()</script>", items: [{ title: "a' onmouseover='b", text: '<iframe>', meta: '&' }] }] }))!;
    const html = renderPage(evil);
    expect(html).not.toMatch(/<script>alert|<img src=x|<iframe>|<script>x\(\)/);
    expect((html.match(/<script>/g) ?? []).length).toBe(1); // only the page's own form script
    expect(esc(`<&>"'`)).toBe('&lt;&amp;&gt;&quot;&#39;');
  });
  it('renders one complete, labelled, themed document', () => {
    const html = renderPage(parseSpec(JSON.stringify(good))!);
    expect(html.startsWith('<!-- AI-generated by BrainyApp2')).toBe(true);
    expect((html.match(/<\/html>/g) ?? []).length).toBe(1);
    expect((html.match(/<h1/g) ?? []).length).toBe(1);
    expect(html).toMatch(/prefers-color-scheme:dark/);
    expect(html).toMatch(/<label for="cf-email">Email<\/label>/);
    expect(html).not.toMatch(/https?:\/\/(?!www\.w3\.org)/); // no network requests
  });
  it('writes a Claude Code prompt without the model', () => {
    const p = claudeCodePrompt('A recipe app', parseSpec(JSON.stringify(good)));
    expect(p).toMatch(/^ROLE:/);
    expect(p).toMatch(/A recipe app/);
    expect(p).toMatch(/SELF-CHECK/);
  });
});
