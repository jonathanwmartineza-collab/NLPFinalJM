// Validates .claude/agents against the studio's rules and regenerates docs/agent-brains.md.
import fs from 'node:fs';
import { rel, listAgents, listSkills, readFrontmatter, TOOLS, COLORS, MODELS, EFFORTS, DEPARTMENTS, toolList } from './lib.mjs';

const errors = [], warnings = [], rows = [];
const skills = new Set(listSkills());
const preloadable = (s) => {
  const f = rel('.claude/skills', s, 'SKILL.md');
  if (!fs.existsSync(f)) return 'missing';
  const { data } = readFrontmatter(f);
  return data && String(data['disable-model-invocation']) === 'true' ? 'not preloadable' : 'ok';
};
let descChars = 0;
const DISPLAY = ['displayName', 'title', 'department', 'personality', 'monogram', 'mission', 'examplePrompts'];

for (const file of listAgents()) {
  const slug = file.replace(/\.md$/, '');
  const { data: d, body, error } = readFrontmatter(rel('.claude/agents', file));
  const bad = (m) => errors.push(`${file}: ${m}`);
  if (error) { bad(error); continue; }
  if (d.name !== slug) bad(`name "${d.name}" must equal the file name "${slug}"`);
  if (!d.description) bad('missing description'); else descChars += String(d.description).length;
  if (!MODELS.includes(d.model)) bad(`invalid model "${d.model}"`);
  if (d.effort !== undefined && !EFFORTS.includes(d.effort)) bad(`invalid effort "${d.effort}"`);
  if (d.model === 'haiku' && d.effort !== undefined) warnings.push(`${file}: effort set on a haiku agent`);
  if (!COLORS.includes(d.color)) bad(`invalid color "${d.color}"`);
  const tools = toolList(d.tools);
  for (const t of tools) if (!TOOLS.includes(t)) bad(`unknown tool "${t}"`);
  if (slug === 'orchestrator' && !tools.includes('Agent')) bad('the orchestrator must have the Agent tool');
  if (!['orchestrator', 'delivery-lead'].includes(slug) && tools.includes('Agent')) bad('only orchestrator and delivery-lead may have the Agent tool');
  for (const s of d.skills ?? []) { const p = preloadable(s); if (p !== 'ok') bad(`preloaded skill "${s}" is ${p}`); }
  if (!d.display || typeof d.display !== 'object') bad('missing display map');
  else {
    for (const k of DISPLAY) if (!d.display[k]) bad(`display.${k} is missing`);
    if (d.display.department && !DEPARTMENTS.includes(d.display.department)) bad(`unknown department "${d.display.department}"`);
    if (Array.isArray(d.display.examplePrompts) && d.display.examplePrompts.length < 3) bad('display.examplePrompts needs 3 prompts');
  }
  if (!fs.existsSync(rel('knowledge', slug, 'README.md'))) warnings.push(`${file}: knowledge/${slug}/README.md not found yet`);
  if (body.split('\n').length < 30) warnings.push(`${file}: system prompt looks short`);
  rows.push([d.display?.displayName, d.display?.title, d.display?.department, d.model, d.effort ?? '', d.display?.personality, (d.skills ?? []).join(', ')]);
}
if (descChars > 12_000) errors.push(`all descriptions together are ${descChars} characters (max 12,000)`);

const order = (r) => DEPARTMENTS.indexOf(r[2]);
rows.sort((a, b) => order(a) - order(b));
const md = `# Agent brains\n\nGenerated by \`npm run validate:team\` from the agent files' frontmatter. Do not edit by hand.\n\n| Name | Title | Department | Model | Effort | Personality | Skills |\n|---|---|---|---|---|---|---|\n${rows.map((r) => `| ${r.map((c) => String(c ?? '').replace(/\|/g, '\\|')).join(' | ')} |`).join('\n')}\n`;
fs.writeFileSync(rel('docs/agent-brains.md'), md);

for (const w of warnings) console.log('WARN', w);
if (errors.length) { for (const e of errors) console.log('FAIL', e); console.log(`validate-team: ${errors.length} error(s)`); process.exit(1); }
console.log(`validate-team: ${rows.length} agents OK, ${skills.size} skills present, descriptions ${descChars} chars`);
